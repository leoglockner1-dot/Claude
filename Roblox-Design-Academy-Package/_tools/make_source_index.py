#!/usr/bin/env python3
"""Build 22-Source-Library/All-External-Links.md: every external URL cited in the package, grouped by domain,
with the notes that cite it. Re-run after adding notes:  python3 _tools/make_source_index.py
Only URLs that appear in notes are listed; the script does not fetch anything, so it says nothing about
whether a URL is still live.
"""
import re, os, glob, collections, urllib.parse
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
OUT = os.path.join('22-Source-Library', 'All-External-Links.md')
url_re = re.compile(r'https?://[^\s)>\]|"\'`]+')
cites = collections.defaultdict(set)
for f in sorted(glob.glob('**/*.md', recursive=True)):
    if os.path.normpath(f) == os.path.normpath(OUT):
        continue
    for u in url_re.findall(open(f, encoding='utf-8').read()):
        u = u.rstrip('.,;:*')
        cites[u].add(f)

def group(u):
    host = urllib.parse.urlparse(u).netloc.lower()
    host = host[4:] if host.startswith('www.') else host
    if host.endswith('roblox.com') and host not in ('devforum.roblox.com', 'create.roblox.com'):
        return 'roblox.com (games, APIs, marketplace)'
    return host

by = collections.defaultdict(list)
for u in cites:
    by[group(u)].append(u)
order = sorted(by, key=lambda h: (-len(by[h]), h))
lines = ['---', 'title: "All External Links (generated)"', 'tags: [source-library, index, generated]',
         'note_type: "index"', '---', '', '# All External Links (generated)', '',
         f'Generated by `_tools/make_source_index.py` from the notes themselves: **{len(cites)} distinct URLs** '
         f'from **{len(by)} hosts**, each listed with the notes that cite it. A listed URL was cited, which is not '
         'the same as being re-checked today. Access results per host are in the [Access Log](Access-Log.md).', '',
         '## Hosts', '', '| Host | URLs |', '|---|---|']
lines += [f'| [{h}](#{re.sub(r"[^a-z0-9 -]", "", h.lower()).replace(" ", "-")}) | {len(by[h])} |' for h in order]
for h in order:
    lines += ['', f'## {h}', '', '| URL | Cited in |', '|---|---|']
    for u in sorted(by[h]):
        notes = sorted(cites[u])
        refs = ', '.join(f'[{os.path.basename(n)[:-3]}](../{n})' for n in notes[:6])
        if len(notes) > 6:
            refs += f' +{len(notes) - 6} more'
        lines.append(f'| <{u}> | {refs} |')
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(f'{len(cites)} URLs, {len(by)} hosts -> {OUT}')
for h in order[:15]:
    print(f'  {len(by[h]):4d}  {h}')
