#!/usr/bin/env python3
"""Regenerate MANIFEST.md from the files actually present: every note (title, type, evidence) and every
asset (category, licence, source). Run from anywhere:  python3 _tools/make_manifest.py
Third-party asset rows come from _tools/asset-sources.json; original assets are attributed to the script
that produced them. Rows for third-party assets are written even when the file has not been fetched yet,
marked "not fetched", so the manifest is the same in a fresh clone and in a full install.
"""
import os, re, glob, json, collections, datetime
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)

def fm(path):
    s = open(path, encoding='utf-8').read()
    meta = {}
    m = re.match(r'---\n(.*?)\n---', s, re.S)
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(':')
            meta[k.strip()] = v.strip().strip('"')
    if 'title' not in meta:
        h = re.search(r'^# (.+)$', s, re.M)
        meta['title'] = h.group(1).strip() if h else os.path.basename(path)[:-3]
    return meta

def cell(t, n=110):
    t = (t or '').replace('|', '/').replace('\n', ' ')
    return t if len(t) <= n else t[:n - 1] + '…'

GEN = [  # (path prefix, generator, purpose)
    ('Assets/Original/Blender/BL-EX-04', '_tools/blender/ex_treasure_chests.py', 'renders, QC JSON, exports'),
    ('Assets/Original/Blender/BL-EX-09', '_tools/blender/ex_modular_kit.py', 'renders, QC JSON, exports'),
    ('Assets/Original/Blender/BL-EX-07', '_tools/blender/ex_extra.py', 'renders, QC JSON, exports'),
    ('Assets/Original/Blender/BL-EX-11', '_tools/blender/ex_extra.py', 'animation export and results'),
    ('Assets/Original/Blender/BL-EX-12', '_tools/blender/ex_extra.py', 'VFX card renders and QC'),
    ('Assets/Original/Blender/', '_tools/blender/ex_props.py', 'renders, QC JSON, exports'),
    ('Assets/Original/AV/', '_tools/av/make_av_previews.py', 'synthesized audio, waveforms, motion previews'),
    ('Assets/Original/UI/BM-03', '_tools/ui/bm03_check.js', 'HUD screenshots and checker results'),
    ('Assets/Original/Luau/', '_tools/luau/run_tests.sh', 'test run logs'),
]

notes = sorted(n for n in glob.glob('**/*.md', recursive=True) if n != 'MANIFEST.md')
registry = json.load(open('_tools/asset-sources.json', encoding='utf-8'))
reg = {os.path.normpath(r['path']): r for r in registry}
originals = sorted(os.path.normpath(a) for a in glob.glob('Assets/Original/**/*', recursive=True) if os.path.isfile(a))
tools = sorted(t for t in glob.glob('_tools/**/*', recursive=True) if os.path.isfile(t) and '__pycache__' not in t)

by_folder = collections.defaultdict(list)
for n in notes:
    by_folder[n.split(os.sep)[0] if os.sep in n else '(root)'].append(n)

out = ['# MANIFEST — Roblox Design Academy 2.0', '',
       f'Generated by `_tools/make_manifest.py` on {datetime.date.today().isoformat()} from the files present. '
       'Do not edit by hand; re-run the script after changes.', '',
       '## Totals', '', '| Item | Count |', '|---|---|',
       f'| Markdown notes (incl. root documents, excl. this file) | {len(notes)} |',
       f'| Original assets (made by this academy, committed) | {len(originals)} |',
       f'| Third-party assets (registry entries, fetched by `_tools/fetch_assets.py`) | {len(registry)} |',
       f'| Tool files in `_tools/` | {len(tools)} |', '',
       '## Import considerations',
       '- Keep the folder structure intact (relative links). No plugins or Dataview are needed.',
       '- Folder and file names contain no spaces, so links work on Windows, macOS and Linux.',
       '- A git clone has only the original assets; third-party images and clips appear after '
       '`python3 _tools/fetch_assets.py`. The ZIP build includes them.',
       '- Video clips are **linked**, not embedded. Images use standard Markdown embeds.',
       '- Third-party game images are for private study only. Roblox docs media is CC BY 4.0.',
       '- Thumbnail CDN URLs in the registry can expire; the fetch script reports failures without overwriting.', '',
       '## Notes by folder', '', '| Folder | Notes |', '|---|---|']
out += [f'| {f} | {len(v)} |' for f, v in sorted(by_folder.items())]
out += ['', '## Every note', '', 'Purpose = title; Type and Evidence from each note\'s frontmatter.', '']
for f, v in sorted(by_folder.items()):
    out += [f'### {f}', '', '| Note | Type | Evidence / source |', '|---|---|---|']
    for n in v:
        m = fm(n)
        src = m.get('evidence') or m.get('source') or ''
        out.append(f'| [{cell(m["title"], 90)}]({n}) | {m.get("note_type", "")} | {cell(src)} |')
    out.append('')

out += ['## Original assets', '', 'Created in this session by the academy\'s own scripts. Licence: original work, '
        'owned by the vault owner; no third-party content.', '',
        '| File | Category | Produced by |', '|---|---|---|']
for a in originals:
    g = next(((s, p) for pre, s, p in GEN if a.startswith(os.path.normpath(pre))), ('(manual)', ''))
    out.append(f'| [{a}]({a}) | {g[1]} | `{g[0]}` |')

out += ['', '## Third-party assets', '', 'From `_tools/asset-sources.json`. **Private study only** unless the licence '
        'says otherwise; do not republish. "not fetched" = run `python3 _tools/fetch_assets.py`.', '',
        '| File | Category | Licence | Source |', '|---|---|---|---|']
for r in registry:
    p = os.path.normpath(r['path'])
    src = r.get('source_url') or (f'derived from {r["from"]}' if r.get('from') else 'contact sheet (inputs in `_tools/contact-sheet-batches.json`)')
    if r.get('source_url'):
        src = f'<{src}>'
    flag = '' if os.path.exists(p) else ' (not fetched)'
    out.append(f'| {p}{flag} | {r.get("category", "")} | {cell(r.get("license", ""), 70)} | {cell(src, 140) if not src.startswith("<") else src} |')

out += ['', '## Tools', '', '| File | Purpose |', '|---|---|']
PURPOSE = {
    'validate_package.py': 'Link, asset, registry and path validator', 'fetch_assets.py': 'Rebuild third-party assets from the registry without overwriting',
    'asset-sources.json': 'Third-party asset registry (licence, source, method)', 'make_manifest.py': 'Generates this file',
    'make_source_index.py': 'Generates 22-Source-Library/All-External-Links.md', 'contact-sheet-batches.json': 'Inputs for contact sheets',
    'make_video_sheet.py': 'Video timing/audio contact sheets', 'run_tests.sh': 'Type-check and run all Luau specs',
}
for t in tools:
    b = os.path.basename(t)
    d = PURPOSE.get(b) or ('Luau module' if t.endswith('.luau') and '/src/' in t else 'Luau spec or benchmark' if t.endswith('.luau')
                          else 'Blender helper/exercise script' if '/blender/' in t else 'UI benchmark file' if '/ui/' in t
                          else 'Audio/motion preview generator' if '/av/' in t else '')
    out.append(f'| `{t}` | {d} |')
open('MANIFEST.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'MANIFEST.md: {len(notes)} notes, {len(originals)} original assets, {len(registry)} third-party, {len(tools)} tools')

# Regenerate the "All notes by folder" part of the Master Index (the hand-written part above it is kept).
mi = os.path.join('00-Start-Here', 'Master-Index.md')
s = open(mi, encoding='utf-8').read()
head = s.split('## All notes by folder')[0]
lines = ['## All notes by folder', '', f'Generated by `_tools/make_manifest.py` ({len(notes)} notes).', '']
for f, v in sorted(by_folder.items()):
    if f == '(root)':
        continue
    lines += [f'### {f} ({len(v)} notes)']
    for n in v:
        rel = os.path.relpath(n, '00-Start-Here').replace(os.sep, '/')
        lines.append(f'- [{fm(n)["title"]}]({rel})')
    lines.append('')
open(mi, 'w', encoding='utf-8').write(head + '\n'.join(lines))
print('Master-Index notes list regenerated')
